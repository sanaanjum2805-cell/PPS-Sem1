#include<stdio.h>
void main()
{
    int i,c,j,n;
    printf("enter the number to generate prime number");
    scanf("%d",&n);

    for(i=1;i<=1;i++)
    {
        c=0;
        for(i=1;i<=n;i++)

        {
          for(j=1;j<=i;j++)
          {
              if(i+j==0)
                c++;
          }
          if(c==2);
          printf("%d\t",i);
        }

    }
}
