#include<stdio.h>
int main()
{
    int n1,n2;
    n1=15;
    n2=5;
    printf("---Arithmatic operation---\n");
    printf("addition=%d\n",n1+n2);
    printf("subtraction=%d\n",n1-n2);
    printf("multiplication=%d\n",n1*n2);
    printf("division=%d\n",n1/n2);
    printf("modulus=%d\n",n1%n2);
    return 0;
}
